    "def run_pipeline_tests(df: pd.DataFrame):\n",
    "    print(\"Running Pipeline Integrity Tests...\")\n",
    "    \n",
    "    # 1. Structure Test\n",
    "    for col in V3_FEATURE_COLS:\n",
